    private void jButtonCreateBookActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonCreateBookActionPerformed
        String title = jTextFieldBookTittle.getText();
        String[] authorsData = jTextAreaAuthors.getText().split("\n");
        String isbn = jTextFieldBookISBN.getText();
        String genre = jComboBoxBookGenero.getItemAt(jComboBoxBookGenero.getSelectedIndex());
        String format = jComboBoxBookFormat.getItemAt(jComboBoxBookFormat.getSelectedIndex());
        String value = jTextFieldBookValor.getText();
        String publisherData = jComboBoxBookPublisher.getItemAt(jComboBoxBookPublisher.getSelectedIndex());
        String pages = jTextFieldNroPages.getText();
        String copies = jTextFieldNroEjemplares.getText();
        String hyperlink = jTextFieldBookHyper.getText();
        String duration = jTextFieldBookDuration.getText();
        String[] narratorData = jComboBoxBookNarrator.getItemAt(jComboBoxBookNarrator.getSelectedIndex()).split(" - ");
        
        Response response = createBook(title, authorsData, isbn, genre, format, value, publisherData, jRadioButtonImpreso.isSelected(), jRadioButtonDigital.isSelected(), jRadioButtonAudioBook.isSelected(), pages, copies, hyperlink, duration, narratorData);
        
        if (response.getStatus() >= 500) {
            JOptionPane.showMessageDialog(null, response.getMessage(), "Error " + response.getStatus(), JOptionPane.ERROR_MESSAGE);
        } else if (response.getStatus() >= 400) {
            JOptionPane.showMessageDialog(null, response.getMessage(), "Error " + response.getStatus(), JOptionPane.WARNING_MESSAGE);
        } else {
            JOptionPane.showMessageDialog(null, response.getMessage(), "Response Message", JOptionPane.INFORMATION_MESSAGE);
        
            jTextFieldBookTittle.setText("");
            jTextFieldBookISBN.setText("");
            jTextFieldBookValor.setText("");
            jTextFieldNroPages.setText("");
            jTextFieldNroEjemplares.setText("");
            jTextAreaAuthors.setText("");
        }
    }//GEN-LAST:event_jButtonCreateBookActionPerformed

